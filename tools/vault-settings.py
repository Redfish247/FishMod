#!/usr/bin/env python3
"""Regenerate vault '04 - Systems/Settings/*.md' from @ConfigValue declarations (names, types, defaults)."""
import os, re, collections

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
SRC = os.path.join(ROOT, "dungeons-26.1.2", "src", "main", "kotlin")
OUT = os.path.join(ROOT, "FishModNew", "04 - Systems", "Settings")
RE_DECL = re.compile(r"\b(?:var|val)\s+(\w+)\s*:\s*([\w<>?,. ]+?)\s*(?:=\s*(.*))?$")
RE_OBJ = re.compile(r"^\s*(?:\w+\s+)*(?:object|class)\s+(\w+)")

# labels from the index: object -> [feature labels]
labels = collections.defaultdict(list)
idx = os.path.join(ROOT, ".codeindex", "index.tsv")
if os.path.exists(idx):
    for ln in open(idx, encoding="utf-8"):
        p = ln.rstrip("\n").split("\t")
        if p[0] == "gui" and len(p) >= 5:
            m = re.search(r"-> (\w+)\.class", p[4])
            if m:
                labels[m.group(1)].append(p[1])

groups = collections.defaultdict(list)  # object -> [(name,type,default,comment,relpath)]
for dp, _, fns in os.walk(SRC):
    for fn in sorted(fns):
        if not fn.endswith(".kt"):
            continue
        p = os.path.join(dp, fn)
        lines = open(p, encoding="utf-8", errors="replace").read().split("\n")
        obj = fn[:-3]
        prev = ""
        pend = False
        for ln in lines:
            m = RE_OBJ.match(ln)
            if m and "@ConfigValue" not in ln and "enum " not in ln and "interface " not in ln and not ln.startswith(" "):
                obj = m.group(1)
            if "@ConfigValue" in ln:
                pend = True
            d = RE_DECL.search(ln)
            if pend and d:
                pend = False
                c = prev.strip()[2:].strip() if prev.strip().startswith("//") else ""
                default = (d.group(3) or "").strip()
                if len(default) > 60:
                    default = default[:57] + "..."
                groups[obj].append((d.group(1), d.group(2).strip(), default, c, os.path.relpath(p, ROOT).replace("\\", "/")))
            if ln.strip():
                prev = ln

os.makedirs(OUT, exist_ok=True)
index = []
for obj, rows in sorted(groups.items()):
    path = rows[0][4]
    lab = labels.get(obj, [])
    out = ["---", "type: system", "updated: 2026-11-15", "---", "", f"# Settings - {obj}", "",
           f"Generated by `tools/vault-settings.py` from `{path}`. Names, types and defaults are FACT as of generation; rerun after settings change. The meaning of a setting is in its feature page or the config screen label.", ""]
    if lab:
        out += ["Config screen entries: " + ", ".join(sorted(set(lab))), ""]
    out += [f"{len(rows)} settings.", "", "| Setting | Type | Default | Note |", "|---|---|---|---|"]
    for n, t, dflt, c, _ in rows:
        out.append(f"| `{n}` | `{t}` | `{dflt.replace('|', '/')}` | {c.replace('|', '/')} |")
    open(os.path.join(OUT, f"Settings - {obj}.md"), "w", encoding="utf-8").write("\n".join(out) + "\n")
    index.append((obj, len(rows), path))

idxp = ["---", "type: system", "updated: 2026-11-15", "---", "", "# Settings Index", "",
        "Every `@ConfigValue` setting, one page per settings holder. Generated by `tools/vault-settings.py` (run from the repo root after `python tools/code-index/build.py`). See also [[Settings Reference]] (hand-written overview) and [[Configuration System]].", "",
        f"{sum(n for _, n, _ in index)} settings in {len(index)} holders.", ""]
for obj, n, path in sorted(index):
    idxp.append(f"- [[Settings - {obj}]] ({n}) - `{path}`")
open(os.path.join(OUT, "Settings Index.md"), "w", encoding="utf-8").write("\n".join(idxp) + "\n")
print(len(index), "pages", sum(n for _, n, _ in index), "settings")
